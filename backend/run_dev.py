"""
Точка входа для превью-инструмента (.claude/launch.json): порт не хардкожен
в команде запуска — читается из переменной окружения PORT, которую
подставляет сам инструмент (autoPort: true), иначе используется 8000 как
запасной вариант для ручного запуска (см. backend/README.md — там команда
без этого враппера, с явным --port, для тех, кто просто открывает /docs
руками, не через превью).

--reload намеренно выключен здесь (в отличие от README) — с ним uvicorn
поднимает отдельный процесс-наблюдатель поверх рабочего, что мешает
превью-инструменту однозначно отслеживать/останавливать один PID.
"""
import os

import uvicorn

if __name__ == "__main__":
    port = int(os.environ.get("PORT", 8000))
    uvicorn.run("app.main:app", host="0.0.0.0", port=port, reload=False)
